import { describe, expect, it } from 'vitest';
import {
  amenityCreateSchema,
  amenityUpdateSchema,
  heroSlideCreateSchema,
  heroSlideUpdateSchema,
  hotelProfileUpdateSchema,
  isAllowedSocialUrl,
  landingSectionUpdateSchema,
  nearbyPlaceCreateSchema,
  nearbyPlaceUpdateSchema,
  reorderSchema,
  roomCreateSchema,
  roomTypeCreateSchema,
  roomTypeImagesSchema,
  roomTypeUpdateSchema,
  roomUpdateSchema,
  socialLinkCreateSchema,
} from './admin.js';

const ID_A = '01a1a882-2549-7326-9bd7-7806f53f0c75';
const ID_B = '01a1a882-2549-7326-9bd7-7806f53f0c76';

describe('admin schemas', () => {
  it('rejects unexpected properties', () => {
    expect(
      roomTypeCreateSchema.safeParse({ name: 'A', type: 'COUPLE', capacity: 2, admin: true })
        .success,
    ).toBe(false);
  });

  it('applies room type defaults and trims text', () => {
    const type = roomTypeCreateSchema.parse({ name: '  Suite  ', type: 'COUPLE', capacity: 2 });
    expect(type).toMatchObject({
      name: 'Suite',
      priceUnit: 'PER_NIGHT',
      taxesIncluded: true,
      amenityIds: [],
    });
  });

  it('has no per-type SEO or short description fields (generated by the web, ADR 0016)', () => {
    for (const field of ['seoTitle', 'seoDescription', 'shortDescription']) {
      expect(roomTypeUpdateSchema.safeParse({ [field]: 'x' }).success).toBe(false);
    }
  });

  it('keeps rooms to a name, a type and a status', () => {
    expect(roomCreateSchema.parse({ name: ' 101 ', roomTypeId: ID_A })).toEqual({
      name: '101',
      roomTypeId: ID_A,
      status: 'DRAFT',
    });
    expect(roomCreateSchema.safeParse({ name: '101' }).success).toBe(false);
    expect(roomUpdateSchema.safeParse({ capacity: 2 }).success).toBe(false);
    expect(roomUpdateSchema.safeParse({ status: 'INACTIVE' }).success).toBe(true);
  });

  it('validates nearby places: a name and optional texts, cleared with ""', () => {
    expect(nearbyPlaceCreateSchema.safeParse({}).success).toBe(false);
    expect(
      nearbyPlaceCreateSchema.parse({
        name: ' Parque principal ',
        distanceText: '',
        category: null,
      }),
    ).toEqual({
      name: 'Parque principal',
      distanceText: null,
      category: null,
      active: true,
    });
    expect(nearbyPlaceUpdateSchema.safeParse({ travelTimeText: 'a'.repeat(81) }).success).toBe(
      false,
    );
  });

  it('keeps landing sections to the switch and the order', () => {
    expect(landingSectionUpdateSchema.safeParse({ enabled: false }).success).toBe(true);
    expect(landingSectionUpdateSchema.safeParse({ title: 'Hola' }).success).toBe(false);
    expect(landingSectionUpdateSchema.safeParse({ mediaAssetId: ID_A }).success).toBe(false);
  });

  it('accepts the hotel tagline, country and WhatsApp greeting, but no hero media', () => {
    expect(
      hotelProfileUpdateSchema.parse({
        tagline: ' Lema ',
        country: 'Colombia',
        whatsappGreeting: '',
      }),
    ).toEqual({ tagline: 'Lema', country: 'Colombia', whatsappGreeting: null });
    expect(hotelProfileUpdateSchema.safeParse({ heroMediaId: ID_A }).success).toBe(false);
  });

  it('turns empty optional text into null', () => {
    expect(hotelProfileUpdateSchema.parse({ legalName: '', mapUrl: '', email: '' })).toEqual({
      legalName: null,
      mapUrl: null,
      email: null,
    });
  });

  it('normalizes and validates the WhatsApp number', () => {
    expect(hotelProfileUpdateSchema.parse({ whatsappNumber: '+57 310 679-8260' })).toEqual({
      whatsappNumber: '573106798260',
    });
    expect(hotelProfileUpdateSchema.safeParse({ whatsappNumber: '0123' }).success).toBe(false);
  });

  it('accepts only https URLs on the expected social hosts', () => {
    expect(isAllowedSocialUrl('INSTAGRAM', 'https://www.instagram.com/hotel')).toBe(true);
    expect(isAllowedSocialUrl('INSTAGRAM', 'https://instagram.com.evil.example/x')).toBe(false);
    expect(
      socialLinkCreateSchema.safeParse({ platform: 'FACEBOOK', url: 'http://facebook.com/x' })
        .success,
    ).toBe(false);
    expect(
      socialLinkCreateSchema.safeParse({ platform: 'FACEBOOK', url: 'https://evil.example' })
        .success,
    ).toBe(false);
    expect(
      socialLinkCreateSchema.safeParse({ platform: 'OTHER', url: 'https://anything.example' })
        .success,
    ).toBe(true);
  });

  it('allows at most one cover and no duplicate images', () => {
    expect(
      roomTypeImagesSchema.safeParse({
        images: [
          { mediaAssetId: ID_A, isCover: true },
          { mediaAssetId: ID_B, isCover: true },
        ],
      }).success,
    ).toBe(false);
    expect(
      roomTypeImagesSchema.safeParse({ images: [{ mediaAssetId: ID_A }, { mediaAssetId: ID_A }] })
        .success,
    ).toBe(false);
  });

  it('rejects duplicate ids when reordering', () => {
    expect(reorderSchema.safeParse({ ids: [ID_A, ID_A] }).success).toBe(false);
  });

  it('defaults amenities to the ROOM scope and accepts only HOTEL or ROOM', () => {
    const amenity = amenityCreateSchema.parse({ name: 'Ventilador', iconKey: 'fan' });
    expect(amenity).toMatchObject({ scope: 'ROOM', active: true, showOnHome: false });
    expect(
      amenityCreateSchema.parse({ name: 'Wi-Fi', iconKey: 'wifi', scope: 'HOTEL' }).scope,
    ).toBe('HOTEL');
    expect(amenityUpdateSchema.safeParse({ scope: 'BUILDING' }).success).toBe(false);
  });

  it('validates hero slides: media required, optional alt override and caption', () => {
    expect(heroSlideCreateSchema.safeParse({}).success).toBe(false);
    expect(heroSlideCreateSchema.parse({ mediaAssetId: ID_A, altText: '', caption: '  ' })).toEqual(
      {
        mediaAssetId: ID_A,
        altText: null,
        caption: null,
        active: true,
      },
    );
    expect(
      heroSlideCreateSchema.safeParse({ mediaAssetId: ID_A, altText: 'a'.repeat(251) }).success,
    ).toBe(false);
    expect(heroSlideUpdateSchema.safeParse({ mediaAssetId: ID_B }).success).toBe(true);
    expect(heroSlideUpdateSchema.safeParse({ position: 1 }).success).toBe(false);
  });
});
