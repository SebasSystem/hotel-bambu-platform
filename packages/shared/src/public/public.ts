import { z } from 'zod';

// ─── Cache tags (requirement 21) ────────────────────────────────────────────

/**
 * Next.js cache tags. The API sends them to `POST /api/revalidate` after admin mutations;
 * the web tags its `fetch` calls with the same values.
 *
 * - `site`: GET /public/site (hotel profile, social links, amenities, hero slides, sections).
 * - `rooms`: the room types and their published room counts (GET /public/room-types).
 * - `nearby`: GET /public/nearby-places.
 */
export const CACHE_TAGS = {
  site: 'site',
  rooms: 'rooms',
  amenities: 'amenities',
  gallery: 'gallery',
  faq: 'faq',
  policies: 'policies',
  nearby: 'nearby',
} as const;

export type StaticCacheTag = (typeof CACHE_TAGS)[keyof typeof CACHE_TAGS];

/** Tag for a single room type page (`/habitaciones/<slug>`). */
export function roomCacheTag(slug: string): `room:${string}` {
  return `room:${slug}`;
}

export const REVALIDATE_SECRET_HEADER = 'x-revalidate-secret';

export const revalidateRequestSchema = z.strictObject({
  tags: z
    .array(
      z
        .string()
        .min(1)
        .max(140)
        .regex(/^[a-z]+(?::[a-z0-9-]+)?$/),
    )
    .min(1)
    .max(50),
});
export type RevalidateRequest = z.infer<typeof revalidateRequestSchema>;

// ─── Analytics (requirement 11) ─────────────────────────────────────────────

export const ANALYTICS_EVENT_TYPES = [
  'PAGE_VIEW',
  'WHATSAPP_CLICK',
  'ROOM_VIEW',
  'MAP_CLICK',
  'SOCIAL_CLICK',
] as const;
export type AnalyticsEventType = (typeof ANALYTICS_EVENT_TYPES)[number];

/** Where the interaction happened (page or UI element). Closed list: no URLs or free text. */
export const ANALYTICS_SOURCES = [
  'home',
  'rooms',
  'room_detail',
  'services',
  'gallery',
  'location',
  'faq',
  'policies',
  'contact',
  'legal',
  'header',
  'hero',
  'room_card',
  'floating',
  'footer',
  /** Kept so stored aggregates still validate; promotions were removed (ADR 0016). */
  'promotion',
  'other',
] as const;
export type AnalyticsSource = (typeof ANALYTICS_SOURCES)[number];

/** Short lowercase identifiers only: no URLs, no free text, nothing that can identify a person. */
const analyticsToken = z
  .string()
  .max(60)
  .regex(/^[a-z0-9][a-z0-9_-]*$/, 'Must be a short lowercase identifier');

export const analyticsEventSchema = z.strictObject({
  type: z.enum(ANALYTICS_EVENT_TYPES),
  source: z.enum(ANALYTICS_SOURCES).optional(),
  /** Related entity: a published room slug or a lowercase social platform key; others are dropped. */
  entityId: analyticsToken.optional(),
});
export type AnalyticsEventInput = z.infer<typeof analyticsEventSchema>;

// ─── Consent evidence (requirement 17.5.9) ──────────────────────────────────

export const CONSENT_CATEGORIES = ['functional', 'analytics', 'marketing'] as const;

export const consentSchema = z.strictObject({
  /** Random id generated by the browser (e.g. crypto.randomUUID()). Never an IP or user id. */
  consentId: z
    .string()
    .min(16)
    .max(64)
    .regex(/^[A-Za-z0-9_-]+$/),
  policyVersion: z
    .string()
    .min(1)
    .max(20)
    .regex(/^[A-Za-z0-9._-]+$/),
  categories: z.strictObject({
    functional: z.boolean(),
    analytics: z.boolean(),
    marketing: z.boolean(),
  }),
});
export type ConsentInput = z.infer<typeof consentSchema>;

// ─── Public response shapes ─────────────────────────────────────────────────

export interface PublicMediaVariant {
  width: number;
  height: number;
  format: 'avif' | 'webp';
  url: string;
}

export interface PublicMedia {
  id: string;
  altText: string;
  caption: string | null;
  width: number | null;
  height: number | null;
  blurDataUrl: string | null;
  dominantColor: string | null;
  variants: PublicMediaVariant[];
}

/** `GET /public/room-types` item: a published room type (ADR 0016). */
export interface PublicRoomTypeSummary {
  slug: string;
  name: string;
  /** RoomKind: INDIVIDUAL | COUPLE | TWIN | FAMILY. */
  type: string;
  description: string | null;
  capacity: number;
  basePrice: number | null;
  currency: string;
  priceUnit: string;
  taxesIncluded: boolean;
  cover: PublicMedia | null;
  /** Published rooms of this type (0 when the hotel has not listed them yet). */
  publishedRoomCount: number;
  /** ISO 8601; last edit of the type (sitemap `lastModified`). */
  updatedAt: string;
  amenities: { name: string; iconKey: string }[];
  /**
   * Bed setup and area, in the list too (D6): room cards show the beds without one detail
   * request per type.
   */
  beds: { type: string; count: number }[] | null;
  areaM2: number | null;
}

/** `GET /public/room-types/:slug` detail. */
export interface PublicRoomTypeDetail extends PublicRoomTypeSummary {
  priceNotes: string | null;
  images: PublicMedia[];
}

/**
 * `GET /public/room-types/:slug` for an old slug (a renamed type or a former per-room URL) answers
 * 200 with `{ redirectTo }` only; the web turns it into a 301.
 */
export interface PublicRoomTypeRedirect {
  redirectTo: string;
}

/** `GET /public/nearby-places` item. */
export interface PublicNearbyPlace {
  id: string;
  name: string;
  category: string | null;
  distanceText: string | null;
  travelTimeText: string | null;
}
